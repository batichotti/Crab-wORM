const ID_PK: &str = "\t\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";

// STRUCT

impl StructMetadata {
    pub fn to_html(&self) -> String {
        let fields: Vec<String> = self
            .fields
            .iter()
            .filter(|f| f.name != "id")
            .map(|f| field_to_html(self.name, f))
            .collect();

        if fields.is_empty() {
            return String::new();
        }

        format!(
            "<form data-table=\"{}\">\n<fieldset>\n<legend>{}</legend>\n{}\n</fieldset>\n\
             <button type=\"submit\">Save</button>\n\
             <output class=\"status\" role=\"status\"></output>\n</form>",
            snake_case(self.name),
            esc(self.name),
            fields.join("\n")
        )
    }

    pub fn to_sql(&self) -> String {
        let columns: Vec<String> = self
            .fields
            .iter()
            .filter(|f| f.name != "id")
            .filter(|f| vec_inner(f.ty).is_none())
            .map(|f| single_column(&format!("{}.{}", self.name, f.name), f.name, f.ty))
            .collect();

        let children: Vec<String> = self
            .fields
            .iter()
            .filter_map(|f| vec_table_def(self.name, f))
            .collect();

        if columns.is_empty() && children.is_empty() {
            return String::new();
        }

        let mut all_columns = vec![String::from(ID_PK)];
        all_columns.extend(columns);

        let mut statements = vec![format!(
            "CREATE TABLE IF NOT EXISTS {} (\n{}\n);",
            table_name(self.name),
            all_columns.join(",\n")
        )];
        statements.extend(children);
        statements.join("\n\n")
    }
}

// ENUM

impl EnumMetadata {
    /// Cartao de referencia: lista as variantes com o id que vai para o banco.
    /// (Como campo de uma struct, o enum vira botoes de escolha ou select.)
    pub fn to_html(&self) -> String {
        if self.variants.is_empty() {
            return String::new();
        }

        let items: String = self
            .variants
            .iter()
            .enumerate()
            .map(|(i, v)| format!("<li><code>{}</code><span>{}</span></li>", i + 1, esc(v)))
            .collect::<Vec<_>>()
            .join("\n");

        format!(
            "<section class=\"enum-card\">\n<h3><span class=\"kw\">enum</span>{}</h3>\n<ol>\n{}\n</ol>\n</section>",
            esc(self.name),
            items
        )
    }

    pub fn to_sql(&self) -> String {
        if self.variants.is_empty() {
            return String::new();
        }

        let values = self
            .variants
            .iter()
            .enumerate()
            .map(|(i, v)| format!("({}, '{}')", i + 1, v.replace('\'', "''")))
            .collect::<Vec<_>>()
            .join(", ");

        let table = table_name(self.name);

        format!(
            "CREATE TABLE IF NOT EXISTS {table} (\n\
             \t\"id\" INTEGER PRIMARY KEY,\n\
             \t\"name\" TEXT NOT NULL UNIQUE\n\
             );\n\
             INSERT INTO {table} (\"id\", \"name\") VALUES {values}\n\
             ON CONFLICT (\"id\") DO UPDATE SET \"name\" = excluded.\"name\";"
        )
    }
}

// WRAPPER

impl TypeMetadata {
    pub fn to_html(&self) -> String {
        match self {
            Self::Struct(s) => s.to_html(),
            Self::Enum(e) => e.to_html(),
        }
    }

    pub fn to_sql(&self) -> String {
        match self {
            Self::Struct(s) => s.to_sql(),
            Self::Enum(e) => e.to_sql(),
        }
    }
}

