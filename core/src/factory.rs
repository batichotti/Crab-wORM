/// Pagina HTML completa: um formulario por struct e um cartao de referencia por enum.
pub fn generate_html() -> String {
    let mut types: Vec<&'static TypeMetadata> =
        inventory::iter::<TypeMetadata>.into_iter().collect();
    types.sort_by_key(|t| t.name());

    let render = |want_struct: bool| -> Vec<String> {
        types
            .iter()
            .filter(|t| matches!(t, TypeMetadata::Struct(_)) == want_struct)
            .map(|t| t.to_html())
            .filter(|s| !s.is_empty())
            .collect()
    };

    let forms = render(true);
    let enums = render(false);

    let enum_section = if enums.is_empty() {
        String::new()
    } else {
        format!(
            "<h2 class=\"section\">Enums</h2>\n<section class=\"enums\">\n{}\n</section>\n",
            enums.join("\n")
        )
    };

    format!(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n\
         <meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>Crab-wORM</title>\n{style}\n</head>\n<body>\n\
         <header class=\"page-head\">\n\
         <h1>Crab-w<span>ORM</span></h1>\n\
         <p>// forms generated from your structs</p>\n\
         </header>\n<main>\n{forms}\n</main>\n{enum_section}{script}\n</body>\n</html>\n",
        style = STYLE,
        forms = forms.join("\n\n"),
        enum_section = enum_section,
        script = SUBMIT_SCRIPT,
    )
}

pub fn generate_sql() -> String {
    let mut all: Vec<&'static TypeMetadata> =
        inventory::iter::<TypeMetadata>.into_iter().collect();

    all.sort_by_key(|t| (matches!(t, TypeMetadata::Struct(_)), t.name()));

    let mut visited: HashSet<&'static str> = HashSet::new();
    let mut ordered: Vec<&'static TypeMetadata> = Vec::new();

    for t in &all {
        visit(t, &all, &mut visited, &mut ordered);
    }

    ordered
        .into_iter()
        .map(|t| t.to_sql())
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// DFS: visita primeiro as dependencias de `t` e so depois o adiciona em `ordered`.
/// O tipo e marcado como visitado antes de descer, o que quebra ciclos.
fn visit(
    t: &'static TypeMetadata,
    all: &[&'static TypeMetadata],
    visited: &mut HashSet<&'static str>,
    ordered: &mut Vec<&'static TypeMetadata>,
) {
    if !visited.insert(t.name()) {
        return; // ja ordenado, ou em andamento (ciclo)
    }

    if let TypeMetadata::Struct(s) = t {
        for f in s.fields {
            let Some(dep_name) = dependency_name(f.ty) else {
                continue;
            };
            if let Some(dep) = all.iter().find(|x| x.name() == dep_name) {
                visit(dep, all, visited, ordered);
            }
        }
    }

    ordered.push(t);
}

fn dependency_name(ty: &str) -> Option<&'static str> {
    let t = strip_option(ty);
    let inner = match vec_inner(&t) {
        Some(v) => strip_option(&v),
        None => t,
    };

    if let Some(e) = find_enum(&inner) {
        return Some(e.name);
    }
    find_struct(&inner).map(|s| s.name)
}

// Identificadores
//
// Todo identificador vai entre aspas duplas e em snake_case. As aspas evitam
// palavras reservadas (`User` -> "user"); o snake_case evita que o Postgres
// diferencie maiusculas de minusculas. Consequencia: na hora de consultar
// a tabela no psql, escreva SELECT * FROM "user";

fn snake_case(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_uppercase() {
            let prev_lower = i > 0 && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit());
            let acronym_end = i > 0
                && chars[i - 1].is_uppercase()
                && chars.get(i + 1).is_some_and(|n| n.is_lowercase());
            if prev_lower || acronym_end {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn quote_ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

/// Nome (ja citado) da tabela de um tipo registrado: `User` -> `"user"`.
fn table_name(type_name: &str) -> String {
    quote_ident(&snake_case(type_name))
}

